-- REGLA COMODÍN (fallback): cualquier monitor SIN regla específica se
-- auto-configura solo — resolución nativa (preferred), posición automática a
-- la derecha (auto) y escala automática según DPI (auto). Esto hace que
-- conectar 2, 3, 4 o N monitores desconocidos "simplemente funcione".
-- El output vacío ("") solo aplica cuando ninguna regla de abajo coincide,
-- así que NO pisa tus monitores específicos.
hl.monitor({
    output = "",
    mode = "preferred",
    position = "auto",
    scale = "auto",
})

